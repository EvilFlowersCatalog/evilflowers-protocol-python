"""Overlay on the generated data layer (:mod:`evilflowers_protocol.schema`).

``schema.py`` is generated by datamodel-codegen from the OpenAPI spec in
``evilflowers-protocol``. That spec is generated by the catalog itself
(``EvilFlowersCatalog/apps/openapi/``) and synced here by
``.github/workflows/generate-client.yml``. The generated models are the source of
truth. This module only gives them stable names and patches what the generator
gets wrong.

Request models subclass the generated forms and override only the broken fields.
Each override is marked ``# upstream:`` and names the generator bug:

* ``EntryForm.identifiers`` is typed ``str``; the backend takes an object.
* ``category_ids``, ``author_ids`` and ``feeds`` are typed as a single UUID; they are lists.
* ``EntryForm.image`` (and ``AcquisitionForm.content``) are ``AnyUrl``; they are
  base64 ``data:`` URIs.

``tests/test_overlay.py`` checks each override against the generated field.
When a regeneration fixes a field upstream, that test fails and the override
should be deleted. When the generated models drift from the overlay (a field
renamed or removed), it fails too.

Response models are deliberately small *projections* rather than subclasses. The
spec on ``main`` marks fields required that the backend sends as null (``summary``,
``citation``, ``image_mime``, ``content``), and it still lists fields the backend no
longer sends (``base64``, ``checksum``). Validating whole serializers would break
on real responses. The same test checks that every projected field still exists
in the corresponding generated serializer.

Request models drop ``None`` values from ``model_dump()``, so an unset optional
field is never sent as ``null``. Unknown fields are rejected, so typos fail early.
"""

from __future__ import annotations

import base64
import mimetypes
import re
from pathlib import Path
from typing import Any, Generic, TypeVar
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from evilflowers_protocol import schema

__all__ = [
    "AcquisitionMeta",
    "AcquisitionRef",
    "AuthorRef",
    "CatalogRef",
    "CategoryRef",
    "EntryConfig",
    "EntryCreate",
    "EntryRef",
    "EntryUpdate",
    "Page",
    "image_data_uri",
]

_DATA_IMAGE_PREFIX = re.compile(r"^data:image/[A-Za-z0-9.+-]+;base64,")

T = TypeVar("T")


def _check_image(value: str | None) -> str | None:
    if value is not None and not _DATA_IMAGE_PREFIX.match(value):
        raise ValueError("image must be a base64 data URI: 'data:image/<type>;base64,<payload>'")
    return value


def image_data_uri(path: Path, mime: str | None = None) -> str:
    """Read an image file and return it as a ``data:image/...;base64,...`` URI.

    This is the format ``EntryCreate.image`` expects. The backend accepts gif, jpeg
    and png up to 5 MB.
    """
    mime = mime or mimetypes.guess_type(path.name)[0]
    if mime is None or not mime.startswith("image/"):
        raise ValueError(f"cannot tell the image type of {path.name!r}; pass mime=")
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{encoded}"


# --------------------------------------------------------------------------- requests


class _Request(BaseModel):
    model_config = ConfigDict(extra="forbid")

    def model_dump(self, **kwargs: Any) -> dict[str, Any]:
        """Like :meth:`pydantic.BaseModel.model_dump`, but ``exclude_none`` defaults to True."""
        kwargs.setdefault("exclude_none", True)
        return super().model_dump(**kwargs)

    def model_dump_json(self, **kwargs: Any) -> str:
        """Like :meth:`pydantic.BaseModel.model_dump_json`, but ``exclude_none`` defaults to True."""
        kwargs.setdefault("exclude_none", True)
        return super().model_dump_json(**kwargs)


class AuthorRef(_Request, schema.AuthorForm):
    """An author given by name (generated ``AuthorForm``)."""


class CategoryRef(_Request, schema.CategoryForm):
    """A category given by term (generated ``CategoryForm``)."""


class EntryConfig(_Request, schema.EntryConfigForm):
    """Per-entry feature flags (generated ``EntryConfigForm``). Unknown keys pass through.

    On ``PUT`` the backend merges this object into the stored config, so keys you
    leave out keep their current values.
    """

    model_config = ConfigDict(extra="allow")


class EntryCreate(_Request, schema.EntryForm):
    """Body of ``POST /catalogs/{catalog_id}/entries`` (generated ``EntryForm``, patched).

    ``identifiers`` keys the backend accepts: ``isbn``, ``doi``, ``google``,
    ``dataverse_pid`` and ``dataverse_dataset_id``. ``image`` is the cover as a base64
    ``data:`` URI (see :func:`image_data_uri`); there is no separate cover endpoint.
    Pass either ``authors`` or ``author_ids`` (and either ``categories`` or
    ``category_ids``), not both. ``authors`` and ``categories`` default to ``[]`` and
    are always sent, and the backend counts an empty list as given. So using
    ``author_ids`` or ``category_ids`` on create currently gets a 422 ("not both").
    """

    authors: list[AuthorRef] = Field(default_factory=list)  # type: ignore[assignment]  # narrowed: non-null
    categories: list[CategoryRef] = Field(default_factory=list)  # type: ignore[assignment]  # narrowed: non-null
    config: EntryConfig | None = None
    # upstream: generated as `str`; the backend takes an object.
    identifiers: dict[str, str] | None = None  # type: ignore[assignment]
    # upstream: generated as `AnyUrl`; the backend takes a base64 data URI.
    image: str | None = None  # type: ignore[assignment]
    # upstream: generated as a single UUID; the backend takes a list.
    category_ids: list[UUID] | None = None  # type: ignore[assignment]
    author_ids: list[UUID] | None = None  # type: ignore[assignment]
    feeds: list[UUID] | None = None  # type: ignore[assignment]

    _image = field_validator("image")(_check_image)


class EntryUpdate(EntryCreate):
    """Body of ``PUT /catalogs/{catalog_id}/entries/{entry_id}``. Fields left as None are not sent.

    The backend does not support partial updates yet: its ``EntryForm`` still
    requires ``title`` and ``language_code`` on ``PUT`` and answers 422 without
    them. Send both until the catalog relaxes this.
    """

    title: str | None = Field(default=None, max_length=255)  # type: ignore[assignment]
    language_code: str | None = Field(default=None, max_length=3)  # type: ignore[assignment]
    authors: list[AuthorRef] | None = None  # type: ignore[assignment]
    categories: list[CategoryRef] | None = None  # type: ignore[assignment]


class AcquisitionMeta(_Request, schema.AcquisitionMetaForm):
    """The ``metadata`` form field of the multipart acquisition upload.

    ``relation`` is one of ``open-access``, ``acquisition``, ``borrow`` or
    ``restricted-access``.
    """

    # narrowed: non-null, so the relation is always sent.
    relation: schema.AcquisitionType = schema.AcquisitionType.open_access


# -------------------------------------------------------------------------- responses


class _Projection(BaseModel):
    model_config = ConfigDict(extra="ignore", frozen=True)


class CatalogRef(_Projection):
    """Projection of the generated ``AppsApiSerializersCatalogsCatalogSerializerBase``."""

    id: UUID
    url_name: str
    title: str


class AcquisitionRef(_Projection):
    """Projection of the generated ``AppsApiSerializersEntriesAcquisitionSerializerBase``.

    ``relation`` and ``mime`` are plain strings: the generated enums lag behind the backend.
    """

    id: UUID
    relation: str
    mime: str


class EntryRef(_Projection):
    """Projection of the generated entry serializers (``...EntrySerializerBase`` / ``...Detailed``).

    List responses carry no ``identifiers``, so the field is ``{}`` there. Identifier
    values the backend stores as null are dropped.
    """

    id: UUID
    title: str
    identifiers: dict[str, str] = Field(default_factory=dict)
    catalog_id: UUID | None = None
    acquisitions: list[AcquisitionRef] = Field(default_factory=list)

    @field_validator("identifiers", mode="before")
    @classmethod
    def _clean_identifiers(cls, value: Any) -> Any:
        if value is None:
            return {}
        if isinstance(value, dict):
            return {str(key): str(item) for key, item in value.items() if item is not None}
        return value

    @field_validator("acquisitions", mode="before")
    @classmethod
    def _none_is_empty(cls, value: Any) -> Any:
        return [] if value is None else value


class Page(BaseModel, Generic[T]):
    """One page of a list endpoint (generated ``AppsApiResponsePaginationResponseModel``).

    The wire format is ``{"items": [...], "metadata": {"page", "limit", "pages",
    "total"}}``. The metadata is lifted to the top level.
    """

    model_config = ConfigDict(extra="ignore")

    items: list[T]
    page: int = 1
    pages: int = 1
    total: int | None = None

    @model_validator(mode="before")
    @classmethod
    def _lift_metadata(cls, data: Any) -> Any:
        if isinstance(data, dict) and isinstance(data.get("metadata"), dict):
            return {**data["metadata"], "items": data.get("items", [])}
        return data
